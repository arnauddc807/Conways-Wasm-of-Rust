const CopyWebpackPlugin = require("copy-webpack-plugin");
const path = require("path");

module.exports = {
  entry: "./bootstrap.js",
  output: {
    path: path.resolve(__dirname, "dist"),
    filename: "bootstrap.js",
    clean: true,
  },
  mode: "development",
  // wasm-pack's bundler output is an ES module that imports the `.wasm`
  // directly; webpack 5 only handles that behind this flag.
  experiments: {
    asyncWebAssembly: true,
  },
  plugins: [
    // Everything the page loads outside the bundle. Previously only the HTML
    // was copied, so a built `dist/` was missing its stylesheet.
    new CopyWebpackPlugin({
      patterns: [
        { from: "index.html" },
        { from: "style.css" },
        { from: "manifest.webmanifest" },
        { from: "sw.js" },
        {
          from: "icons",
          to: "icons",
          // The icons are generated by a script that lives beside them; ship
          // the PNGs, not the generator.
          globOptions: { ignore: ["**/*.py"] },
        },
      ],
    }),
  ],
  devServer: {
    // Bound to every interface so the dev server is reachable from a phone on
    // the same network — testing touch handling in a desktop browser only gets
    // you so far.
    host: "0.0.0.0",
    port: 8080,
    allowedHosts: "all",
    static: {
      directory: path.resolve(__dirname, "dist"),
    },
  },
};
